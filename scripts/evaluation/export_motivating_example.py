"""
Export the motivating example artifacts for a single Test2NL entry: the natural
language description, the ground truth test, and the tests generated by NL2Test
and by the Gemini CLI baseline, as standalone files alongside a metadata file.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from cldk import CLDK
from cldk.analysis.java import JavaAnalysis

from sakura.test2nl.model.models import Test2NLEntry
from sakura.utils.analysis.java_analyzer import CommonAnalysis
from sakura.utils.file_io.structured_data_manager import StructuredDataManager

ROOT_DIR = Path(__file__).resolve().parent.parent.parent

TEST2NL_FILE = ROOT_DIR / "resources/test2nl/filtered_dataset/test2nl.csv"
DATASETS_DIR = ROOT_DIR / "resources/datasets"
ANALYSIS_DIR = ROOT_DIR / "resources/analysis"
NL2TEST_EVAL_DIR = ROOT_DIR / "outputs/raw_outputs/nl2test_gemini_pro_output"
GEMINI_CLI_EVAL_DIR = ROOT_DIR / "outputs/raw_outputs/gemini_cli_pro_output"
OUTPUT_DIR = ROOT_DIR / "outputs/motivating_example"

EVAL_FILE_NAME = "nl2test_evaluation_results.json"

# Default exemplar: the circular inheritance detection test from commons-bcel,
# whose localized decomposition is exported alongside it as
# localized_scenario.json.
DEFAULT_ENTRY_ID = 280

# Both generators exported here are backed by Gemini 2.5 Pro.
GENERATOR_MODEL = "gemini-2.5-pro"

DESCRIPTION_FILE_NAME = "description.md"
GROUND_TRUTH_FILE_NAME = "ground_truth_test.java"
NL2TEST_FILE_NAME = "nl2test_generated_test.java"
GEMINI_CLI_FILE_NAME = "gemini_cli_generated_test.java"
METADATA_FILE_NAME = "metadata.json"


def load_test2nl_entry(test2nl_file: Path, entry_id: int) -> Test2NLEntry:
    """Load the single Test2NL entry with the given id."""
    manager = StructuredDataManager(test2nl_file.parent)
    entries = manager.load(test2nl_file.name, Test2NLEntry, format="csv")

    matches = [entry for entry in entries if entry.id == entry_id]
    if not matches:
        raise ValueError(f"No Test2NL entry with id {entry_id} in {test2nl_file}")
    if len(matches) > 1:
        raise ValueError(
            f"Duplicate Test2NL entries with id {entry_id} in {test2nl_file}"
        )

    return matches[0]


def load_evaluation_entry(eval_dir: Path, entry_id: int) -> dict[str, Any]:
    """Load the evaluation record for the given id from a raw output directory."""
    if not eval_dir.is_dir():
        raise FileNotFoundError(f"Evaluation directory not found: {eval_dir}")

    for project_dir in sorted(eval_dir.iterdir()):
        eval_file = project_dir / EVAL_FILE_NAME
        if not project_dir.is_dir() or not eval_file.is_file():
            continue

        with eval_file.open("r", encoding="utf-8") as f:
            data = json.load(f)

        for record in data:
            if record.get("nl2test_input", {}).get("id") == entry_id:
                return record

    raise ValueError(f"No evaluation record with id {entry_id} under {eval_dir}")


def extract_generated_test(record: dict[str, Any], eval_dir: Path) -> str:
    """Extract the generated test source from an evaluation record."""
    code = (record.get("nl2test_metadata") or {}).get("code")
    if not code or not code.strip():
        raise ValueError(
            f"Evaluation record from {eval_dir} contains no generated code"
        )
    return code


def load_analysis(
    project_name: str, datasets_dir: Path, analysis_dir: Path
) -> tuple[JavaAnalysis, CommonAnalysis]:
    """Load the CLDK analysis for a dataset project."""
    project_dir = datasets_dir / project_name
    if not project_dir.is_dir():
        raise FileNotFoundError(f"Dataset project not found: {project_dir}")

    analysis_project_dir = analysis_dir / project_name
    if not (analysis_project_dir / "analysis.json").is_file():
        raise FileNotFoundError(
            f"Analysis not found for project: {analysis_project_dir}"
        )

    analysis: JavaAnalysis = CLDK(language="java").analysis(
        project_path=str(project_dir),
        analysis_json_path=str(analysis_project_dir),
        eager=False,
    )
    return analysis, CommonAnalysis(analysis)


def find_source_file(
    analysis: JavaAnalysis,
    qualified_class_name: str,
    project_dir: Path,
) -> Path | None:
    """Locate the Java source file declaring a class, if it is still on disk."""
    for file_path, compilation_unit in analysis.get_symbol_table().items():
        if qualified_class_name not in compilation_unit.type_declarations:
            continue

        recorded = Path(file_path)
        if recorded.is_file():
            return recorded

        # The analysis records absolute paths from the machine that produced it,
        # so re-root the path under the local dataset checkout when it has moved.
        parts = recorded.parts
        if project_dir.name in parts:
            index = len(parts) - 1 - parts[::-1].index(project_dir.name)
            relocated = project_dir.joinpath(*parts[index + 1 :])
            if relocated.is_file():
                return relocated

    return None


def get_ground_truth_test(
    analysis: JavaAnalysis,
    common: CommonAnalysis,
    qualified_class_name: str,
    method_signature: str,
    project_dir: Path,
) -> str:
    """Extract the ground truth test method, preferring the verbatim source."""
    cldk_class_name = CommonAnalysis.get_cldk_class_name(qualified_class_name)
    cldk_method_signature = CommonAnalysis.get_cldk_method_sig(
        qualified_class_name, method_signature
    )

    method = analysis.get_method(cldk_class_name, cldk_method_signature)
    if not method:
        method = analysis.get_method(
            cldk_class_name,
            CommonAnalysis.simplify_method_signature(cldk_method_signature),
        )
    if not method:
        raise ValueError(
            f"Ground truth method not found: {qualified_class_name}.{method_signature}"
        )

    source_file = find_source_file(analysis, cldk_class_name, project_dir)
    if source_file and method.start_line and method.end_line:
        lines = source_file.read_text(encoding="utf-8").splitlines()
        snippet = lines[method.start_line - 1 : method.end_line]
        if snippet:
            return "\n".join(snippet) + "\n"

    # Fall back to the code the analysis reconstructed, which is reformatted and
    # carries annotations separately from the declaration.
    annotations = "\n".join(method.annotations or [])
    code = common.get_complete_method_code(method.declaration, method.code)
    return (f"{annotations}\n{code}" if annotations else code).rstrip() + "\n"


def render_description(entry: Test2NLEntry) -> str:
    """Render the natural language description as a readable Markdown document."""
    return "\n".join(
        [
            "# Natural Language Test Description",
            "",
            entry.description.strip(),
            "",
        ]
    )


def as_java_file(code: str) -> str:
    """Normalize generated Java source for writing to disk."""
    return code.strip() + "\n"


def relative_to_root(path: Path) -> str:
    """Render a path relative to the repository root when possible."""
    try:
        return str(path.relative_to(ROOT_DIR))
    except ValueError:
        return str(path)


def build_metadata(
    entry: Test2NLEntry,
    nl2test_record: dict[str, Any],
    gemini_cli_record: dict[str, Any],
    test2nl_file: Path,
    nl2test_eval_dir: Path,
    gemini_cli_eval_dir: Path,
) -> dict[str, Any]:
    """Build the metadata record describing the exported motivating example."""

    def generated_metadata(
        record: dict[str, Any], eval_dir: Path, file_name: str
    ) -> dict:
        metadata = record.get("nl2test_metadata") or {}
        return {
            "file": file_name,
            "model": GENERATOR_MODEL,
            "source_dir": relative_to_root(eval_dir),
            "qualified_test_class_name": metadata.get("qualified_test_class_name"),
            "method_signature": metadata.get("method_signature"),
            "compiles": record.get("compiles"),
        }

    abstraction_level = entry.abstraction_level
    return {
        "id": entry.id,
        "project_name": entry.project_name,
        "qualified_class_name": entry.qualified_class_name,
        "method_signature": entry.method_signature,
        "abstraction_level": (abstraction_level.value if abstraction_level else None),
        "is_bdd": entry.is_bdd,
        "description": {
            "file": DESCRIPTION_FILE_NAME,
            "source_csv": relative_to_root(test2nl_file),
        },
        "ground_truth_test": {
            "file": GROUND_TRUTH_FILE_NAME,
            "qualified_class_name": entry.qualified_class_name,
            "method_signature": entry.method_signature,
        },
        "nl2test_generated_test": generated_metadata(
            nl2test_record, nl2test_eval_dir, NL2TEST_FILE_NAME
        ),
        "gemini_cli_generated_test": generated_metadata(
            gemini_cli_record, gemini_cli_eval_dir, GEMINI_CLI_FILE_NAME
        ),
    }


def write_example(
    output_dir: Path,
    description: str,
    ground_truth_test: str,
    nl2test_test: str,
    gemini_cli_test: str,
    metadata: dict[str, Any],
) -> list[Path]:
    """Write the motivating example files, returning their paths."""
    output_dir.mkdir(parents=True, exist_ok=True)

    contents = {
        DESCRIPTION_FILE_NAME: description,
        GROUND_TRUTH_FILE_NAME: ground_truth_test,
        NL2TEST_FILE_NAME: nl2test_test,
        GEMINI_CLI_FILE_NAME: gemini_cli_test,
        METADATA_FILE_NAME: json.dumps(metadata, indent=4, ensure_ascii=True) + "\n",
    }

    written: list[Path] = []
    for file_name, content in contents.items():
        path = output_dir / file_name
        path.write_text(content, encoding="utf-8")
        written.append(path)

    return written


def build_parser() -> argparse.ArgumentParser:
    """Build the CLI argument parser."""
    parser = argparse.ArgumentParser(
        description=(
            "Export the description, ground truth test, NL2Test generated test, "
            "and Gemini CLI generated test for one Test2NL entry."
        )
    )
    parser.add_argument(
        "--entry-id",
        type=int,
        default=DEFAULT_ENTRY_ID,
        help="Test2NL id of the entry to export.",
    )
    parser.add_argument(
        "--test2nl-file",
        type=Path,
        default=TEST2NL_FILE,
        help="Path to the Test2NL CSV file.",
    )
    parser.add_argument(
        "--nl2test-eval-dir",
        type=Path,
        default=NL2TEST_EVAL_DIR,
        help="Raw output directory holding the NL2Test evaluation results.",
    )
    parser.add_argument(
        "--gemini-cli-eval-dir",
        type=Path,
        default=GEMINI_CLI_EVAL_DIR,
        help="Raw output directory holding the Gemini CLI evaluation results.",
    )
    parser.add_argument(
        "--datasets-dir",
        type=Path,
        default=DATASETS_DIR,
        help="Directory holding the dataset project checkouts.",
    )
    parser.add_argument(
        "--analysis-dir",
        type=Path,
        default=ANALYSIS_DIR,
        help="Directory holding the per-project CLDK analysis.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=OUTPUT_DIR,
        help="Directory to write the motivating example into.",
    )
    return parser


def main() -> None:
    """Run the motivating example exporter."""
    parser = build_parser()
    args = parser.parse_args()

    test2nl_file: Path = args.test2nl_file
    if not test2nl_file.is_file():
        raise FileNotFoundError(f"Test2NL CSV not found: {test2nl_file}")

    entry = load_test2nl_entry(test2nl_file, args.entry_id)
    nl2test_record = load_evaluation_entry(args.nl2test_eval_dir, args.entry_id)
    gemini_cli_record = load_evaluation_entry(args.gemini_cli_eval_dir, args.entry_id)

    analysis, common = load_analysis(
        entry.project_name, args.datasets_dir, args.analysis_dir
    )
    ground_truth_test = get_ground_truth_test(
        analysis,
        common,
        entry.qualified_class_name,
        entry.method_signature,
        args.datasets_dir / entry.project_name,
    )

    metadata = build_metadata(
        entry,
        nl2test_record,
        gemini_cli_record,
        test2nl_file,
        args.nl2test_eval_dir,
        args.gemini_cli_eval_dir,
    )
    written = write_example(
        args.output_dir,
        description=render_description(entry),
        ground_truth_test=ground_truth_test,
        nl2test_test=as_java_file(
            extract_generated_test(nl2test_record, args.nl2test_eval_dir)
        ),
        gemini_cli_test=as_java_file(
            extract_generated_test(gemini_cli_record, args.gemini_cli_eval_dir)
        ),
        metadata=metadata,
    )

    print(
        f"Exported Test2NL entry {entry.id} "
        f"({entry.project_name} :: {entry.qualified_class_name}.{entry.method_signature})"
    )
    for path in written:
        print(f"  wrote {path}")


if __name__ == "__main__":
    main()
